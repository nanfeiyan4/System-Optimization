WITH RECURSIVE seq(x) AS (SELECT 1 UNION ALL SELECT x+1 FROM seq WHERE x<40000)
  INSERT INTO t SELECT x, 'name_' || x || '_payload', (x % 1000) / 7.0 FROM seq;
WITH RECURSIVE seq(x) AS (SELECT 1 UNION ALL SELECT x+1 FROM seq WHERE x<8000)
  INSERT INTO u SELECT x, 's_' || (x*37 % 997) FROM seq;
CREATE INDEX idx_c ON t(c);
CREATE INDEX idx_b ON t(b);
